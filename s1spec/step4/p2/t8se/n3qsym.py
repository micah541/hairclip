"""Lemma N3' (LEMMA_F.md 6.1), modulation part Q: symbolic ingredients, written to n3qforms.py (arb code).

Exactly (LEMMA_F 6.1), with K(e) := -(J/alpha) kappa_ss, U := (x1 + th c) q + (x2 + th b) t1 and c0 = -3k'^2 - 4k k'':
    N + Q = (1 - th) N + th e'''' + th k^2 e'' - th c0 e + th P + g e' - (th c + x1) e,
    P := (k''' - r') e e'/alpha,   g := U/alpha + 5 th k k'.
The weak-form part needs the Hessian of P in z = (e, e', e'') and its base x-derivatives (h2P, Xh2P, XXh2P);
the strong-form part needs (1/alpha)^(m), m <= 4 (Leibniz with the Frenet jets of q, t1 is done numerically).
dX: k_i -> k_{i+1}, r_i -> r_{i+1} (z fixed).  Output n3qforms.py:
    invalpha(V) -> [(1/alpha)^(m) for m = 0..4]  (V: k0..k4, e0..e4; affine in the top jet e_m)
    hessP(V)    -> dict h2P, Xh2P, XXh2P over PAIRS (V: k0..k5, r1..r3, e0, e1)
usage: python3 -I n3qsym.py   (a few seconds)"""
import os
import sympy as sp

HERE = os.path.dirname(os.path.abspath(__file__))
E = sp.symbols('e0:6'); K = sp.symbols('k0:7'); R = sp.symbols('r1:5')
PAIRS = [(i, j) for i in range(3) for j in range(i, 3)]


def Dfull(f):
    return sum(sp.diff(f, E[i]) * E[i + 1] for i in range(5)) + sum(sp.diff(f, K[i]) * K[i + 1] for i in range(6))


def dX(f):
    return sum(sp.diff(f, K[i]) * K[i + 1] for i in range(6)) + sum(sp.diff(f, R[i]) * R[i + 1] for i in range(3))


class _Pr(sp.printing.str.StrPrinter):
    def _print_Rational(self, e): return f"(arb({e.p})/arb({e.q}))"
    def _print_Integer(self, e): return f"arb({e.p})"
    def _print_Pow(self, e, rational=False):
        bb, ex = e.as_base_exp(); s = f"({self._print(bb)})"
        if ex.is_Integer:
            m = int(ex); prod = "*".join([s] * abs(m)); return f"({prod})" if m > 0 else f"(1/({prod}))"
        raise ValueError(f'unsupported power {e}')


def emit(name, exprs, out):
    syms = sorted(set().union(*[f.free_symbols for f in exprs]), key=str)
    rep, red = sp.cse(exprs, optimizations='basic'); pr = _Pr()
    out.append(f'def {name}(V):')
    for s in syms: out.append(f'    {s} = V["{s}"]')
    for lhs, rhs in rep: out.append(f'    {lhs} = {pr.doprint(rhs)}')
    out.append('    return [' + ', '.join(pr.doprint(e) for e in red) + ']')
    out.append('')


def main():
    al = 1 - K[0] * E[0]
    inv = [1 / al]
    for m in range(4): inv.append(sp.together(Dfull(inv[-1])))
    for m in range(1, 5):                              # affine in the top jet, with coefficient k/alpha^2
        assert sp.simplify(sp.diff(inv[m], E[m], 2)) == 0 and sp.simplify(sp.diff(inv[m], E[m]) - K[0] / al ** 2) == 0
    phi = K[3] - R[0]
    P = phi * E[0] * E[1] / al
    z = (E[0], E[1], E[2])
    h2 = [sp.simplify(sp.diff(P, z[i], z[j])) for i, j in PAIRS]
    Xh2 = [sp.simplify(dX(h)) for h in h2]; XXh2 = [sp.simplify(dX(h)) for h in Xh2]
    assert all(not f.has(R[3]) and not f.has(K[6]) for f in h2 + Xh2 + XXh2)
    out = ['"""generated by n3qsym.py: arb ingredients for the Q part of Lemma N3\' (do not edit)"""', 'from flint import arb', '',
           'PAIRS = ' + repr(PAIRS), '']
    emit('invalpha', inv, out)
    emit('_hessP', h2 + Xh2 + XXh2, out)
    out.append('def hessP(V):')
    out.append('    v = _hessP(V); n = len(PAIRS)')
    out.append('    return dict(h2P=v[:n], Xh2P=v[n:2 * n], XXh2P=v[2 * n:])')
    with open(os.path.join(HERE, 'n3qforms.py'), 'w') as f: f.write('\n'.join(out) + '\n')
    print('wrote n3qforms.py')


def check_split():
    """Machine check of the split of N + Q (LEMMA_F 6.1).  kappa_ss is kept opaque (Kss at e, Kss0 at e = 0); its linearisation
    is the one of the linear operator L (T1 signs.py): DK(0)e = -e4 - k^2 e2 - 5 k k' e1 + c0 e0.  True modulation:
    c_x = (1 - th) c - x1, b_x = (1 - th) b - x2, kappa_ss -> (1 - th) kappa_ss; base varpi, theta_tau, V with the T1/T6 identities."""
    p, q, n, t1, c, b, x, Q, A, r, r1, th, x1, x2, Kss, Kss0 = sp.symbols('p q n t1 c b x Q A r r1 th x1 x2 Kss Kss0')
    e0, e1, e2, e3, e4 = E[:5]; k0, k1, k2, k3 = K[:4]
    al = 1 - k0 * e0; J = sp.sqrt(al ** 2 + e1 ** 2)
    w = -k0 * k1 + Q + c * (q - x) + b * t1 + A
    tht = -k3 - k0 ** 2 * k1 + k0 * Q - c * x * k0 + r1 + k0 * A
    V = -k2 + c * p + b * n + r

    def F(cc, bb, s_, ks, at0):
        a_ = 1 if at0 else al; J_ = 1 if at0 else J; E1 = 0 if at0 else e1; E0 = 0 if at0 else e0
        return (J_ / a_) * (-s_ * ks + cc * (-q * E1 + (p + E0) * a_) / J_ + bb * (-t1 * E1 + n * a_) / J_) - V + E1 * (w - E0 * tht) / a_
    c0 = -3 * k1 ** 2 - 4 * k0 * k2
    DF0 = (-e4 - k0 ** 2 * e2 - 5 * k0 * k1 * e1 + c0 * e0) + c * (e0 - q * e1) - b * t1 * e1 + w * e1
    Nn = F(c, b, 1, Kss, False) - F(c, b, 1, Kss0, True) - DF0
    cx, bx = (1 - th) * c - x1, (1 - th) * b - x2
    NQ = F(cx, bx, 1 - th, Kss, False) - F(cx, bx, 1 - th, Kss0, True) - DF0
    U_ = (x1 + th * c) * q + (x2 + th * b) * t1
    split = ((1 - th) * Nn + th * e4 + th * k0 ** 2 * e2 - th * c0 * e0 + th * (k3 - r1) * e0 * e1 / al
             + (U_ / al + 5 * th * k0 * k1) * e1 - (th * c + x1) * e0)
    assert sp.simplify(sp.expand(NQ - split)) == 0, 'split of N + Q'
    print('checked: N + Q = (1 - th) N + th e4 + th k^2 e2 - th c0 e + th P + g e1 - (th c + x1) e')


if __name__ == '__main__':
    check_split()
    main()
