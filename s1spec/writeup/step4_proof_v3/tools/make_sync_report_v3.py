#!/usr/bin/env python3
"""make_sync_report_v3.py: write the per-edit section of SYNC_REPORT_v3.md (old/new text and source of every edit)
from the EDITS list of apply_sync_v3.py.  It executes only the definitions of apply_sync_v3.py (up to the line
'text = base'), so it writes nothing but tools/edits_v3.md.
Usage: nice -n 19 python3 -I make_sync_report_v3.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "apply_sync_v3.py"), encoding="utf-8").read()
defs = src[: src.index("\ntext = base")]
ns = {"__file__": os.path.join(HERE, "apply_sync_v3.py")}
exec(compile(defs, "apply_sync_v3.py(defs)", "exec"), ns)
base = ns["base"]

out = ["## Appendix: every edit, old and new text (generated by tools/make_sync_report_v3.py)", ""]
for eid, old, new, srcs in ns["EDITS"]:
    line = base[: base.index(old)].count("\n") + 1
    out.append(f"### {eid} (v2 line {line})")
    out.append(f"Source: {srcs}")
    out.append("")
    out.append("Old:")
    out.append("```")
    out.append(old)
    out.append("```")
    out.append("New:")
    out.append("```")
    out.append(new)
    out.append("```")
    out.append("")
with open(os.path.join(HERE, "edits_v3.md"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
print("wrote", os.path.join(HERE, "edits_v3.md"), len(ns["EDITS"]), "edits")
