#!/usr/bin/env python3
"""fix4_r3: old (baseline = v35 numbers, run 'base') vs new (R3 run) for every numeric leaf of the chain outputs.  Read-only on the snapshots.
usage: python3 -B compare_r3.py <old_snapshot_dir> <new_snapshot_dir> <out.md>
A leaf is either an exported number {arb|double, label, bound} or a plain float/int.  Prints (and writes as markdown):
  (1) every leaf whose path contains 'margin' or lies under a 'margins' dict (all margins of the chain, changed or not),
  (2) every other leaf that changed (relative change > 1e-15), with new/old.
Label: the leaf's own 'label' if it has one; margins dicts of assembly_rep (arb lower bounds) and assemble_U (flo of arb) -> cert;
zone3 'at_fine_est' -> est; otherwise the label of the nearest labelled ancestor, else '-' (unlabelled in the source)."""
import sys, os, json
OLD, NEW, OUTMD = sys.argv[1:4]
FILES = ['t2_A/A_interface.json', 't2_A/asm_design_N2ref.json', 't2_A/asm_design_N2ref4.json', 't2_A/asm_design_N20.json', 't2_A/asm_lo_N2ref.json',
         't2_A/asm_hi_N2ref.json', 't2_A/asm_probe_N2ref.json', 't2_A/asm_design_pm3ibp.json', 't4_cert/u1_ghat.json', 't4_cert/u2_K.json',
         't4_cert/u34_primary.json', 't4_cert/U_cert_r3_pass1.json', 't4_cert/U_cert_r3_pass2.json', 't4_cert/U_cert_r3_pass3.json',
         't5_zone3/zone3_interface_pass1.json', 't5_zone3/zone3_interface.json']
import math
def val(d):
    if isinstance(d, dict):
        if 'arb' in d and isinstance(d['arb'], list) and len(d['arb']) == 3:      # arbio (mid mantissa, exponent, radius): midpoint (radius < 1e-50 relative here)
            m, e, r = d['arb']; return math.ldexp(float(int(m)), int(e)) if int(m) else 0.0
        if 'double' in d: return d['double']
        if 'arb' in d and isinstance(d['arb'], str):
            s = d['arb'].strip('[]').split('+/-')[0].strip()
            try: return float(s)
            except ValueError: return None
    if isinstance(d, (int, float)) and not isinstance(d, bool): return float(d)
    if isinstance(d, str):
        s = d.strip()
        if s.startswith('[') and '+/-' in s:
            try: return float(s.strip('[]').split('+/-')[0])
            except ValueError: return None
    return None
def walk(d, p, lab, out):
    if isinstance(d, dict):
        if 'args' in d and p == '': d = {k: v for k, v in d.items() if k != 'args'}
        if ('double' in d or 'arb' in d) and val(d) is not None: out[p] = (val(d), d.get('label', lab), d.get('bound')); return
        l2 = d.get('label', lab) if isinstance(d.get('label'), str) and len(d.get('label', '')) < 12 else lab
        for k, v in d.items():
            if k in ('args',): continue
            walk(v, p + '/' + str(k), l2, out)
    elif isinstance(d, list):
        for i, v in enumerate(d): walk(v, '%s[%d]' % (p, i), lab, out)
    else:
        v = val(d)
        if v is not None: out[p] = (v, lab, None)
def label_of(f, p, l):
    if 'at_fine_est' in p or '_est' in p.split('/')[-1]: return 'est'
    if l: return l
    if '/margins/' in p and ('asm_' in f or 'U_cert' in f): return 'cert'
    return '-'
rows_m, rows_c = [], []
for f in FILES:
    a, b = {}, {}
    walk(json.load(open(os.path.join(OLD, f))), '', None, a); walk(json.load(open(os.path.join(NEW, f))), '', None, b)
    for p in sorted(set(a) | set(b)):
        if p not in a or p not in b: rows_c.append((f, p, a.get(p, (None,))[0], b.get(p, (None,))[0], None, 'missing')); continue
        (x, l, bd), (y, _, _) = a[p], b[p]
        r = (y/x) if x not in (0, None) and y is not None else None
        ch = (x != y) and not (r is not None and abs(r - 1) <= 1e-15)
        ism = ('margin' in p.lower()) or ('/margins/' in p) or p.endswith('/margins')
        row = (f, p, x, y, r, label_of(f, p, l))
        if ism: rows_m.append(row)
        elif ch: rows_c.append(row)
def fmt(v): return '-' if v is None else ('%.6g' % v)
with open(OUTMD, 'w') as o:
    o.write('# fix4_r3 old (base = v35 numbers) vs new (R3)\n\nGenerated by `r3/compare_r3.py %s %s`. ratio = new/old. Label from the source file (see the script docstring).\n\n' % (OLD, NEW))
    o.write('## (1) every margin leaf (changed or not): %d rows\n\n| file | path | old | new | new/old | label |\n|---|---|---|---|---|---|\n' % len(rows_m))
    for f, p, x, y, r, l in rows_m: o.write('| %s | `%s` | %s | %s | %s | %s |\n' % (f, p, fmt(x), fmt(y), ('%.6f' % r) if r is not None else '-', l))
    o.write('\n## (2) every other changed numeric leaf: %d rows\n\n| file | path | old | new | new/old | label |\n|---|---|---|---|---|---|\n' % len(rows_c))
    for f, p, x, y, r, l in rows_c: o.write('| %s | `%s` | %s | %s | %s | %s |\n' % (f, p, fmt(x), fmt(y), ('%.6f' % r) if r is not None else '-', l))
print('margin rows', len(rows_m), 'changed other rows', len(rows_c))
mm = [r for r in rows_m if r[4] is not None and r[4] < 1 - 1e-12]
print('margins that decreased:', len(mm)); worst = sorted(mm, key=lambda r: r[4])[:15]
for f, p, x, y, r, l in worst: print('  %-36s %-70s %.6g -> %.6g  x%.6f [%s]' % (f, p[:70], x, y, r, l))
low = sorted([r for r in rows_m if r[3] is not None and 0 < r[3] < 1.3 and 'against' not in r[1]], key=lambda r: r[3])[:12]
print('smallest new margin values (< 1.3):'); [print('  %-36s %-70s new %.6g (old %.6g) [%s]' % (f, p[:70], y, x, l)) for f, p, x, y, r, l in low]
