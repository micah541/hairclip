# Combined sups as in rhs_iv._ei_v4: far TF = max(ZA, ZB) (ZA = [16.25,34.25], ZB = [34.25,60]); global TG = max(TF, IR).
# Rounding: 'up' constants are rounded up to 5 significant digits, 'down' (MU1, MU2) down.  Level: the 2.5e-4 tables (production march alpha <= 1.6e-4).
# Usage: PYTHONHASHSEED=0 nice -n 19 python3 -B gen_ei_constants_v41.py <out_dir>
import json, sys, os, hashlib
from decimal import Decimal as Dc, ROUND_CEILING, ROUND_FLOOR, getcontext
getcontext().prec = 50
SRC = '/home/claude/s1spec/step3nl_v4c/v4cert/out/constants_v4.json'
D = json.load(open(SRC)); C = D['constants']
def rnd(x, n, up):
    x = Dc(repr(x)); e = x.adjusted(); q = Dc(1).scaleb(e - n + 1)
    r = x.quantize(q, rounding=ROUND_CEILING if up else ROUND_FLOOR)
    if len(r.as_tuple().digits) > n: return rnd(float(r), n, up)
    return r
def tex(x, n=5, up=True):
    r = rnd(x, n, up); e = r.adjusted(); d = ''.join(map(str, r.as_tuple().digits)).ljust(n, '0')[:n]
    if -2 <= e <= 4: return format(r, 'f')
    return f"{d[0]}.{d[1:]}\\cdot10^{{{e}}}"
L = '0.00025'
def T(z, k): return C[f'TQ[{L}][{z}][{k}]']['value']
def TF(k): return max(T('ZA', k), T('ZB', k))
def TG(k): return max(TF(k), T('IR', k))
rows = []   # (symbol, value_tex, raw, key, meaning)
def add(sym, val, key, meaning, up=True): rows.append((sym, tex(val, 5, up), val, key, meaning))
for k in ['MU1', 'MU2']: add(k, C[k]['value'], k, 'G\\aa rding rates (lower bounds)', up=False)
for k, m in [('E1', 'sup|e1|'), ('E0', 'sup|e0|'), ('PSI1', 'sup psi\''), ('PSI2', 'sup|psi\'^2-psi\'\'|'), ('KAP_IR', 'kappa IR'), ('KAP_Z1', 'kappa Z1'), ('KAP_OR', 'kappa OR'),
             ('RWR', 'sup_IR (W/rho)^1/2'), ('KWIR', '1/W(16.25)'), ('AF', 'a_f'), ('BF', 'b_f'), ('CF0', 'c3 coef'), ('CF1', 'c2 coef'), ('CF2', 'c1 coef'), ('CF3', 'c0 coef'),
             ('k4_1', ''), ('k4_2', ''), ('k4_3', ''), ('k4_4', ''), ('k3_1', ''), ('k3_2', ''), ('k3_3', ''), ('Z2i', 'sup_IR|zeta\'\'|'),
             ('T0', ''), ('T2', ''), ('TC0', ''), ('TC2', ''), ('Q2B', ''), ('NAB', ''), ('NP3', ''), ('NH2', ''), ('NP12', ''), ('C0P', ''), ('C0Hb', ''),
             ('FNW0', ''), ('FNW1', ''), ('FNW2', ''), ('FNWd0', ''), ('FNWd1', ''), ('FNWd2', ''), ('FN0', ''), ('FN1', ''), ('C3', ''),
             ('CAB0', ''), ('CAB0_dlead', ''), ('MAB', ''), ('QAB', ''), ('PHIAB', ''), ('BETA0', ''), ('BETA0_dlead', ''), ('BETA1', ''), ('QB', ''), ('BETAF', ''),
             ('SF_ab_0', ''), ('SF_ab_al', ''), ('SF_ab_1', ''), ('SF_ab_2', ''), ('SF_ab_3', ''), ('SF_beta_0', ''), ('SF_beta_al', ''), ('SF_beta_1', ''), ('SF_beta_2', ''), ('SF_beta_3', ''),
             ('PHI34', 'Phi(34.25)'), ('KW', ''), ('PSI1W', '')]:
    add(k, C[k]['value'], k, m)
for k in ['c', 'c_a', 'c_b', 'd010', 'd010_a', 'd010_b', 'd100', 'd100_a', 'd100_b', 'd200', 'd200_a', 'd200_b', 'd110', 'd110_a', 'd110_b', 'd300', 'd300_a', 'd300_b', 'A0', 'A1', 'B0', 'B1', 'EA0', 'EA1', 'DQ0', 'DQ1']:
    add('IR.' + k, T('IR', k), f'TQ[{L}][IR][{k}]', 'inner ramp')
    add('F.' + k, TF(k), f'max(TQ[{L}][ZA][{k}], TQ[{L}][ZB][{k}])', 'far [16.25,60]')
for k in ['c', 'c_a', 'c_b', 'EA0', 'DQ0', 'DQ1']:
    add('G.' + k, TG(k), f'max(far, IR) {k}', 'global [10.25,60]')
